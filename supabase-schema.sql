-- RAW WAY FIT client assessment database (new install + migration-safe)
-- Run in Supabase SQL Editor. Keep RLS enabled.

create extension if not exists pgcrypto;

create table if not exists public.trainer_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.trainer_users enable row level security;
drop policy if exists "Trainer can read own membership" on public.trainer_users;
create policy "Trainer can read own membership" on public.trainer_users
for select to authenticated using (user_id = auth.uid());

create table if not exists public.client_assessments (
  id uuid primary key default gen_random_uuid(),
  client_number bigint generated by default as identity unique,
  created_at timestamptz not null default now(),
  client_name text not null,
  client_email text not null,
  phone text not null,
  declaration boolean not null default false,
  client_confirmation text,
  assessment_data jsonb not null default '{}'::jsonb,
  training_status text not null default 'Lead' check (training_status in ('Lead','Active','On hold','Completed')),
  trainer_summary text,
  initial_plan text,
  next_review_date date,
  updated_at timestamptz not null default now()
);

-- Safe additions for projects where the starter table already exists.
alter table public.client_assessments add column if not exists client_number bigint generated by default as identity;
alter table public.client_assessments add column if not exists training_status text not null default 'Lead';
alter table public.client_assessments alter column client_email drop not null;
create unique index if not exists client_assessments_client_number_uidx on public.client_assessments(client_number);
create index if not exists client_assessments_created_at_idx on public.client_assessments(created_at desc);
create index if not exists client_assessments_client_name_idx on public.client_assessments(lower(client_name));
create index if not exists client_assessments_client_email_idx on public.client_assessments(lower(client_email));
create index if not exists client_assessments_training_status_idx on public.client_assessments(training_status);

alter table public.client_assessments enable row level security;
-- Submissions are made through the server-side Edge Function, not direct browser inserts.
drop policy if exists "Anyone can submit assessment" on public.client_assessments;
drop policy if exists "Approved trainers can view assessments" on public.client_assessments;
create policy "Approved trainers can view assessments" on public.client_assessments
for select to authenticated using (exists (select 1 from public.trainer_users tu where tu.user_id = auth.uid()));
drop policy if exists "Approved trainers can update assessments" on public.client_assessments;
create policy "Approved trainers can update assessments" on public.client_assessments
for update to authenticated
using (exists (select 1 from public.trainer_users tu where tu.user_id = auth.uid()))
with check (exists (select 1 from public.trainer_users tu where tu.user_id = auth.uid()));
drop policy if exists "Approved trainers can delete assessments" on public.client_assessments;
create policy "Approved trainers can delete assessments" on public.client_assessments
for delete to authenticated
using (exists (select 1 from public.trainer_users tu where tu.user_id = auth.uid()));
grant delete on public.client_assessments to authenticated;

create or replace function public.protect_trainer_fields_on_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  new.trainer_summary := null;
  new.initial_plan := null;
  new.next_review_date := null;
  new.training_status := 'Lead';
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists client_assessments_protect_trainer_fields on public.client_assessments;
create trigger client_assessments_protect_trainer_fields before insert on public.client_assessments
for each row execute function public.protect_trainer_fields_on_insert();

create or replace function public.set_client_assessment_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end;
$$;
drop trigger if exists client_assessments_set_updated_at on public.client_assessments;
create trigger client_assessments_set_updated_at before update on public.client_assessments
for each row execute function public.set_client_assessment_updated_at();

